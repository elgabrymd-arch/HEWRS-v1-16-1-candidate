'use strict';
const assert = require('node:assert/strict');
const P = require('../src/ai-five-exclusion.js');
const suit = (n, watch='watch-1', shoe='shoe-8') => ({suitId:`S${String(n).padStart(2,'0')}`, shirtId:'DS001', state:'T001', shoeId:shoe, watchId:watch});
const initial = Array.from({length:20},(_,i)=>suit(i+1));
const a=suit(1,'watch-4');
const b=suit(21,'watch-2');
const c=suit(21,'watch-3');
const d=suit(1,'watch-7','shoe-9'); // Shoes are part of the complete look.
const e=suit(22);const f=suit(23);const g=suit(24);
const r=P.choose(initial,[a,b,c,d,e,f,g]);
assert.equal(r.diagnostics.base_count,20);
assert.equal(r.diagnostics.overlap_with_hewrs,1);
assert.equal(r.diagnostics.duplicate_ai_look,1);
assert.equal(r.options.length,5);
assert.deepEqual(r.options,[b,d,e,f,g]);
assert.equal(P.assertDisjoint(initial,r.options),true);
assert.throws(()=>P.assertDisjoint(initial,[a]),/duplicates/);
assert.throws(()=>P.assertDisjoint(initial,[b,c]),/repeated/);
assert.throws(()=>P.choose([],[]),/Actual current/);
assert.throws(()=>P.choose(initial,[],{limit:6}),/capped at five/);
const invalid=P.choose(initial,[{shirtId:'DS001'},suit(25)]);
assert.equal(invalid.diagnostics.invalid_identity,1);
assert.equal(invalid.options.length,1);
const withBlazer=(pant,watch)=>({blazerId:'B03',pantId:pant,shirtId:'DS007',state:'NO_TIE',shoeId:'shoe-12',watchId:watch});
assert.equal(P.garmentKey(withBlazer('PG002','watch-A')),P.garmentKey(withBlazer('PG002','watch-Z')));
assert.notEqual(P.garmentKey(withBlazer('PG002','watch-A')),P.garmentKey(withBlazer('PG003','watch-A')));
const before=JSON.stringify(initial);
P.choose(initial,[suit(26)]);
assert.equal(JSON.stringify(initial),before);
console.log('PASS ai-five exclusion: 20 base, watch-only collision, intra-AI collision, shoe/trouser distinction, fail-closed, no input mutation');
